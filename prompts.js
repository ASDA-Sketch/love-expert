/**
 * 构建引用回复生成的用户提示词
 * context 放在最前面，让 AI 先看到人物背景。
 * @param {string} quotedMessage - 用户引用的对方那句话/那段话
 * @param {string} style - 回复风格/意图
 * @param {string} customIntent - 当 style="guide_topic" 时，用户指定的目标话题（可选）
 * @param {string} context - 联系人资料+历史对话上下文（可选）
 * @returns {string} 拼接好的用户消息
 */
function buildReplyUserPrompt(quotedMessage, style, customIntent, context) {
  var styleLabels = {
    'auto': '智能推荐',
    'humor': '幽默调侃',
    'sincere': '真诚走心',
    'tease': '俏皮撩拨',
    'flirty': '暧昧推进',
    'empathy': '关心安慰',
    'defuse': '高情商化解',
    'guide_topic': '引导话题',
    'curious': '制造好奇',
    'challenge': '适度挑战',
    'steady': '稳重得体',
    'appreciate': '赞美欣赏',
    'resonance': '共鸣认同',
    'cool': '高冷神秘',
    'sunny': '阳光开朗'
  };
  var styleLabel = styleLabels[style] || style;

  var prompt = '';

  // 联系人资料和完整聊天记录放在最前面，让 AI 先看到人物背景和对话脉络
  if (context && context.trim()) {
    prompt += '以下是当前联系人的资料和完整的聊天记录（注意：这是当前正在对话的联系人，回复只针对此人）：\n';
    prompt += context;
    prompt += '\n\n请认真分析以上信息：此人的性格标签、关系阶段、背景备注、最近情绪状态（从消息推断）、上次聊到什么话题、整个对话的走势（升温/降温/平稳）。你生成的回复必须贴合这些信息，不能千篇一律。\n';
    prompt += '回复要承接前面的对话脉络，不能脱离上下文单独回复对方最后那句话。\n';
    prompt += '每条回复的 reason 必须点明你是基于此人的哪些背景信息和聊天上下文来决定这个语气和内容的。\n\n';
  }

  prompt += '对方最新说了这句话（这是你需要回复的）：\n「' + quotedMessage + '」\n\n';

  if (style === 'auto') {
    prompt += '请用「智能推荐」的方式生成回复：根据以上完整聊天记录和联系人背景，自动判断最合适的回复风格和内容。你可以混合多种风格（幽默/真诚/关心/俏皮等），选择最适合当前对话语境和对方情绪的那一种，给出最自然、最合适的回复。\n';
    prompt += '在 reason 中说明你为什么选择这个风格和内容方向，要结合聊天上下文来解释。\n';
  } else {
    prompt += '请用「' + styleLabel + '」的风格生成回复，同时结合上面的聊天上下文。\n';
  }

  if (style === 'guide_topic' && customIntent) {
    prompt += '用户想把话题引到：' + customIntent + '\n请生成能自然过渡到这个话题的回复，过渡要顺滑不生硬。\n';
  } else if (style === 'guide_topic') {
    prompt += '用户想把话题引导到一个新方向，但由于未指定具体话题，请生成能自然转移话题方向的回复。\n';
  }

  prompt += '\n请按指定 JSON 格式输出 2~3 条回复。';
  return prompt;
}

